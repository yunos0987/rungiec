#!/usr/bin/env python3
"""Generate or check the arity dispatch table (_RUNGIEC_SERIES_N / _RUNGIEC_PARALLEL_N) of rungiec_st.iec, the node table (_RUNGIEC_IS_NODE_<K>0) of rungiec.iec and the generated part of rungiec_ld.iec.

Usage:
    python tools/gen_arity_table.py              print the arity table block for --max 32 to stdout
    python tools/gen_arity_table.py --max 8      print an arity table that stops at N = 8
    python tools/gen_arity_table.py --nodes      print the node table block to stdout
    python tools/gen_arity_table.py --ld         print the generated part of rungiec_ld.iec to stdout
    python tools/gen_arity_table.py --check      compare the arity table with rungiec_st.iec, the node table
                                                 with rungiec.iec and the generated part with rungiec_ld.iec
                                                 (3 lines), exit 1 on any mismatch

The arity table (the ST mode, rungiec_st.iec) holds one real define per N = 1..max for SERIES and
PARALLEL (no {#if} and no trap; the arity limit is checked by _RUNGIEC_ARITY_CHECK in rungiec.iec). The block starts at
the _RUNGIEC_SERIES_1 define and ends at the _RUNGIEC_PARALLEL_<max> define. The macro bodies
come from arity_body() below; to change the form of the table, change arity_body() and
generate the table again. --max applies to the arity table only.

The node table (the entry file rungiec.iec, read by the WIRE checks of both modes) holds one define
_RUNGIEC_IS_NODE_<K>0 per node number K = 0..64. WIRE pastes
_RUNGIEC_IS_NODE_ before and 0 after a node number, so only the integer literals 0..64 hit
the table. The block starts at the _RUNGIEC_IS_NODE_00 define and ends at the
_RUNGIEC_IS_NODE_640 define.

The generated part of rungiec_ld.iec (the LD mode) is every line between the marker lines
(* BEGIN GENERATED by tools/gen_arity_table.py --ld *) and (* END GENERATED *). It holds the set
operations for sets of 0..32 IDs, the network node operations for nodes 0..64, the argument scan of
the boxes for 0..32 call arguments, the tag table, and the macros on the evaluation path, one copy per
depth L = 0..16 (jiepp does not expand a macro inside itself): the tag dispatch _RUNGIEC_LD_EV<L>, the
element dispatch (with JMP, RETURN, the boxes and ST_EXEC), and for L = 0..15 the combinators with
their child lists for N = 1..32 (the combinators of depth 16 are only the nesting check). The bodies
come from generate_ld() below.
"""
import argparse
import difflib
import os
import sys

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS_DIR)

ARITY_FILE = os.path.join(ROOT, "rungiec_st.iec")
NODE_FILE = os.path.join(ROOT, "rungiec.iec")
ARITY_HARD_MAX = 32
BLOCK_FIRST_PREFIX = "{#define _RUNGIEC_SERIES_1("
BLOCK_LAST_PREFIX = "{#define _RUNGIEC_PARALLEL_%d("
NODE_TABLE_MAX = 64
NODE_FIRST_PREFIX = "{#define _RUNGIEC_IS_NODE_00 "
NODE_LAST_PREFIX = "{#define _RUNGIEC_IS_NODE_%d0 " % NODE_TABLE_MAX

LD_FILE = os.path.join(ROOT, "rungiec_ld.iec")
LD_BEGIN = "(* BEGIN GENERATED by tools/gen_arity_table.py --ld *)"
LD_END = "(* END GENERATED *)"
LD_DEPTH_MAX = 16      # _RUNGIEC_LD_EV<L> for L = 0..16; the combinators of L = 16 only check the nesting
LD_ARITY_MAX = 32      # _RUNGIEC_LD_SER<L>_<N> / _RUNGIEC_LD_PAR<L>_<N> for N = 1..32
LD_FANIN_TABLE = 32    # set operations for sets of 0..32 IDs (RUNGIEC_LD_FANIN_MAX is 1..32)
# The elements: (name, parameters). The tag is _RUNGIEC_LD_<name>_T and the output macro _RUNGIEC_LD_<name>_E
# (hand-written in rungiec_ld.iec).
LD_ELEMENTS = (
    ("CONTACT", "x"), ("NOT_CONTACT", "x"), ("RISE_CONTACT", "x"), ("FALL_CONTACT", "x"),
    ("NOT_RISE_CONTACT", "x"), ("NOT_FALL_CONTACT", "x"),
    ("EQ_CONTACT", "a, b"), ("NE_CONTACT", "a, b"), ("GT_CONTACT", "a, b"), ("GE_CONTACT", "a, b"),
    ("LT_CONTACT", "a, b"), ("LE_CONTACT", "a, b"),
    ("COIL", "x"), ("NOT_COIL", "x"), ("SET_COIL", "x"), ("RESET_COIL", "x"), ("RISE_COIL", "x"),
    ("FALL_COIL", "x"),
)
# JMP and RETURN: tags without an ID (the object has no output), output macro _RUNGIEC_LD_<name>_E(params, i, o).
LD_EXITS = (("JMP", "x"), ("RETURN", ""))
# The boxes and ST_EXEC: tags with variable arguments; output macro _RUNGIEC_LD_<name>_E(i, o, args...), which takes
# its IDs itself (in the order of the objects it writes).
LD_BOXES = ("FB_SCAN", "FB_IN", "FB_BOX", "FB_EXEC", "FB_ENO", "FBT_SCAN", "FBT_IN", "FBT_BOX", "FBT_EXEC", "FBT_ENO",
            "FUN_EXEC", "FUN_EXEC_RET", "FUN_ENO", "FUN_ENO_RET", "ST_EXEC")
LD_ARGS_MAX = 32       # _RUNGIEC_LD_ARGS_<n> for n = 0..32 call arguments of a box
LD_COMBINATORS = ("SER", "PAR")


def arity_body(kind, count):
    """Return the body of _RUNGIEC_<kind>_<count> (kind SERIES or PARALLEL) with the parameters c1..c<count>."""
    first = "RungiecAcc := RungiecIn;" if kind == "SERIES" else "RungiecAcc := false;"
    letter = "S" if kind == "SERIES" else "P"
    items = " ".join("_RUNGIEC_%s(c%d)" % (letter, i) for i in range(1, count + 1))
    return "_RUNGIEC_PUSH() %s %s _RUNGIEC_POP()" % (first, items)


def params(count):
    return ", ".join("c%d" % i for i in range(1, count + 1))


def real(kind, count):
    return "{#define _RUNGIEC_%s_%d(%s) %s}" % (kind, count, params(count), arity_body(kind, count))


def generate(max_n):
    """Return the table block as a list of lines."""
    lines = []
    for count in range(1, max_n + 1):
        lines.append(real("SERIES", count))
        lines.append(real("PARALLEL", count))
    return lines


def extract_block(text, max_n):
    """Return the table block of an rungiec_st.iec text as a list of lines, or None if not found."""
    lines = text.split("\n")
    first = next((i for i, ln in enumerate(lines) if ln.startswith(BLOCK_FIRST_PREFIX)), None)
    if first is None:
        return None
    last_prefix = BLOCK_LAST_PREFIX % max_n
    last = next((i for i in range(first, len(lines)) if lines[i].startswith(last_prefix)), None)
    if last is None:
        return None
    return lines[first:last + 1]


def generate_nodes():
    """Return the node table block as a list of lines (K = 0..NODE_TABLE_MAX)."""
    return ["{#define _RUNGIEC_IS_NODE_%d0 1}" % k for k in range(0, NODE_TABLE_MAX + 1)]


def extract_node_block(text):
    """Return the node table block of an rungiec.iec text as a list of lines, or None if not found."""
    lines = text.split("\n")
    first = next((i for i, ln in enumerate(lines) if ln.startswith(NODE_FIRST_PREFIX)), None)
    if first is None:
        return None
    last = next((i for i in range(first, len(lines)) if lines[i].startswith(NODE_LAST_PREFIX)), None)
    if last is None:
        return None
    return lines[first:last + 1]


def ld_slot(k):
    """The ID in slot k of the set p (an expression of rungiec_ld.iec)."""
    return "_RUNGIEC_LD_GET(_RUNGIEC_LD_S(p, %d))" % k


def generate_ld():
    """Return the generated part of rungiec_ld.iec (the lines between the markers) as a list of lines."""
    lines = []
    add = lines.append
    add("(* Set operations for sets of 0 to %d IDs, chosen by the size of the set. *)" % LD_FANIN_TABLE)
    add("{#define _RUNGIEC_LD_CP_0(s, d)}")
    for k in range(1, LD_FANIN_TABLE + 1):
        add("{#define _RUNGIEC_LD_CP_%d(s, d) _RUNGIEC_LD_CP_%d(s, d)_RUNGIEC_LD_SET(_RUNGIEC_LD_S(d, %d), "
            "_RUNGIEC_LD_GET(_RUNGIEC_LD_S(s, %d)))}" % (k, k - 1, k - 1, k - 1))
    add("{#define _RUNGIEC_LD_AP_0(s, d)}")
    for k in range(1, LD_FANIN_TABLE + 1):
        add("{#define _RUNGIEC_LD_AP_%d(s, d) _RUNGIEC_LD_AP_%d(s, d)_RUNGIEC_LD_PUSH(d, "
            "_RUNGIEC_LD_GET(_RUNGIEC_LD_S(s, %d)))}" % (k, k - 1, k - 1))
    add("{#define _RUNGIEC_LD_HAS_0(p, v) FALSE}")
    for k in range(1, LD_FANIN_TABLE + 1):
        add("{#define _RUNGIEC_LD_HAS_%d(p, v) _RUNGIEC_LD_HAS_%d(p, v) || %s = v}" % (k, k - 1, ld_slot(k - 1)))
    add("{#define _RUNGIEC_LD_CN_0(p)}")
    for k in range(1, LD_FANIN_TABLE + 1):
        add("{#define _RUNGIEC_LD_CN_%d(p) _RUNGIEC_LD_CN_%d(p)<Connection refConnectionPointOutId=__xmlattr(%s)/>}"
            % (k, k - 1, ld_slot(k - 1)))
    add("{#define _RUNGIEC_LD_RC_0(p)}")
    for k in range(1, LD_FANIN_TABLE + 1):
        add("{#define _RUNGIEC_LD_RC_%d(p) _RUNGIEC_LD_RC_%d(p)<ConnectionPointIn><Connection "
            "refConnectionPointOutId=__xmlattr(%s)/></ConnectionPointIn>}" % (k, k - 1, ld_slot(k - 1)))
    add("(* Network nodes 0 to %d: _RUNGIEC_LD_NET_CLEAR(id) sets node 0 to the left power rail id and empties the "
        "other nodes and their read flags; _RUNGIEC_LD_NET_RAIL() collects the nodes that no WIRE read into the "
        "right power rail set. *)" % NODE_TABLE_MAX)
    add("{#define _RUNGIEC_LD_NET_CLEAR(id) _RUNGIEC_LD_ONE(_rungiec_ld_n0, id)%s}" % "".join(
        "_RUNGIEC_LD_SET(_rungiec_ld_n%d_n, 0)_RUNGIEC_LD_SET(_rungiec_ld_nr%d, 0)" % (k, k)
        for k in range(1, NODE_TABLE_MAX + 1)))
    add("{#define _RUNGIEC_LD_NET_RAIL() _RUNGIEC_LD_CLR(_rungiec_ld_r)%s}" % "".join(
        "_RUNGIEC_CAT_X(_RUNGIEC_LD_NR_, _RUNGIEC_LD_GET(_rungiec_ld_nr%d))(_rungiec_ld_n%d)" % (k, k)
        for k in range(1, NODE_TABLE_MAX + 1)))
    add("(* Argument scan of the boxes for 0 to %d call arguments, chosen by the number of arguments: scan p of each "
        "argument (_RUNGIEC_LD_ARG). *)" % LD_ARGS_MAX)
    add("{#define _RUNGIEC_LD_ARGS_MAX %d}" % LD_ARGS_MAX)
    add("{#define _RUNGIEC_LD_ARGS_0(p)}")
    for count in range(1, LD_ARGS_MAX + 1):
        add("{#define _RUNGIEC_LD_ARGS_%d(p, %s) %s}" % (
            count, ", ".join("a%d" % i for i in range(1, count + 1)),
            "".join("_RUNGIEC_LD_ARG(p, a%d)" % i for i in range(1, count + 1))))
    add("(* Tag table: a tag gives _RUNGIEC_LD_TAG (checked by _RUNGIEC_LD_CHECK). *)")
    for name in [e[0] for e in LD_ELEMENTS] + [e[0] for e in LD_EXITS] + list(LD_BOXES) + list(LD_COMBINATORS):
        add("{#define _RUNGIEC_LD_IS__RUNGIEC_LD_%s_T(...) _RUNGIEC_LD_TAG}" % name)
    add("(* Depth tables: L = 0 to %d (the combinators of depth %d only check the nesting), N = 1 to %d. *)"
        % (LD_DEPTH_MAX, LD_DEPTH_MAX, LD_ARITY_MAX))
    for lv in range(LD_DEPTH_MAX + 1):
        nx = lv + 1
        add("{#define _RUNGIEC_LD_D%d(a, b) a@@b}" % lv)
        add("{#define _RUNGIEC_LD_EV%d(node) _RUNGIEC_LD_CHECK(node)_RUNGIEC_LD_D%d(_RUNGIEC_LD_EV%d_, node)}"
            % (lv, lv, lv))
        for name, plist in LD_ELEMENTS:
            add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_%s_T(%s) _RUNGIEC_LD_%s_E(%s, __counter(_rungiec_ld_id), "
                "_rungiec_ld_i%d, _rungiec_ld_o%d)}" % (lv, name, plist, name, plist, lv, lv))
        for name, plist in LD_EXITS:
            add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_%s_T(%s) _RUNGIEC_LD_%s_E(%s_rungiec_ld_i%d, _rungiec_ld_o%d)}"
                % (lv, name, plist, name, plist + ", " if plist else "", lv, lv))
        for name in LD_BOXES:
            add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_%s_T(...) _RUNGIEC_LD_%s_E(_rungiec_ld_i%d, _rungiec_ld_o%d, "
                "__VA_ARGS__)}" % (lv, name, name, lv, lv))
        check = "__assert(%d < RUNGIEC_NEST_MAX, RUNGIEC LD: nesting exceeds RUNGIEC_NEST_MAX)" % lv
        if lv == LD_DEPTH_MAX:
            add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_SER_T(...) %s}" % (lv, check))
            add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_PAR_T(...) %s}" % (lv, check))
            continue
        add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_SER_T(...) %s_RUNGIEC_LD_COPY(_rungiec_ld_i%d, _rungiec_ld_i%d)"
            "_RUNGIEC_CAT_X(_RUNGIEC_LD_SER%d_, __VA_ARGC__)(__VA_ARGS__)_RUNGIEC_LD_COPY(_rungiec_ld_o%d, _rungiec_ld_o%d)}"
            % (lv, check, lv, nx, lv, nx, lv))
        add("{#define _RUNGIEC_LD_EV%d__RUNGIEC_LD_PAR_T(...) %s_RUNGIEC_LD_CLR(_rungiec_ld_o%d)"
            "_RUNGIEC_CAT_X(_RUNGIEC_LD_PAR%d_, __VA_ARGC__)(__VA_ARGS__)}" % (lv, check, lv, lv))
        add("{#define _RUNGIEC_LD_SS%d(c) _RUNGIEC_LD_COPY(_rungiec_ld_o%d, _rungiec_ld_i%d)_RUNGIEC_LD_EV%d(c)}"
            % (lv, nx, nx, nx))
        add("{#define _RUNGIEC_LD_PP%d(c) _RUNGIEC_LD_COPY(_rungiec_ld_i%d, _rungiec_ld_i%d)_RUNGIEC_LD_EV%d(c)"
            "_RUNGIEC_LD_APPEND(_rungiec_ld_o%d, _rungiec_ld_o%d)}" % (lv, lv, nx, nx, nx, lv))
        for count in range(1, LD_ARITY_MAX + 1):
            ser = "_RUNGIEC_LD_EV%d(c1)" % nx + "".join("_RUNGIEC_LD_SS%d(c%d)" % (lv, i) for i in range(2, count + 1))
            par = "".join("_RUNGIEC_LD_PP%d(c%d)" % (lv, i) for i in range(1, count + 1))
            add("{#define _RUNGIEC_LD_SER%d_%d(%s) %s}" % (lv, count, params(count), ser))
            add("{#define _RUNGIEC_LD_PAR%d_%d(%s) %s}" % (lv, count, params(count), par))
    return lines


def extract_ld_block(text):
    """Return the lines between the markers of an rungiec_ld.iec text, or None if a marker is not found."""
    lines = text.split("\n")
    first = next((i for i, ln in enumerate(lines) if ln == LD_BEGIN), None)
    if first is None:
        return None
    last = next((i for i in range(first + 1, len(lines)) if lines[i] == LD_END), None)
    if last is None:
        return None
    return lines[first + 1:last]


def print_diff(have, want, name="rungiec.iec"):
    diff = difflib.unified_diff(have, want, name, "generated", lineterm="", n=0)
    for shown, line in enumerate(diff):
        if shown >= 20:
            print("... (diff truncated)")
            break
        print(line[:200])


def check_arity(text, max_n):
    want = generate(max_n)
    have = extract_block(text, max_n)
    if have is None:
        print("gen_arity_table: CHECK FAILED: the table block was not found in rungiec_st.iec")
        return 1
    if have == want:
        print("gen_arity_table: OK (N = 1..%d, %d lines match rungiec_st.iec)" % (max_n, len(want)))
        return 0
    print("gen_arity_table: CHECK FAILED: rungiec_st.iec differs from the generated table")
    print_diff(have, want, "rungiec_st.iec")
    return 1


def check_nodes(text):
    want = generate_nodes()
    have = extract_node_block(text)
    if have is None:
        print("gen_arity_table: CHECK FAILED: the node table block was not found in rungiec.iec")
        return 1
    if have == want:
        print("gen_arity_table: OK (nodes 0..%d, %d lines match rungiec.iec)" % (NODE_TABLE_MAX, len(want)))
        return 0
    print("gen_arity_table: CHECK FAILED: rungiec.iec differs from the generated node table")
    print_diff(have, want)
    return 1


def check_ld():
    try:
        with open(LD_FILE, encoding="utf-8", newline="") as f:
            text = f.read().replace("\r\n", "\n")
    except OSError as exc:
        print("gen_arity_table: CHECK FAILED: cannot read rungiec_ld.iec (%s)" % exc)
        return 1
    want = generate_ld()
    have = extract_ld_block(text)
    if have is None:
        print("gen_arity_table: CHECK FAILED: the generated part markers were not found in rungiec_ld.iec")
        return 1
    if have == want:
        print("gen_arity_table: OK (LD depth 0..%d, N = 1..%d, sets 0..%d, %d lines match rungiec_ld.iec)"
              % (LD_DEPTH_MAX, LD_ARITY_MAX, LD_FANIN_TABLE, len(want)))
        return 0
    print("gen_arity_table: CHECK FAILED: rungiec_ld.iec differs from the generated part")
    print_diff(have, want, "rungiec_ld.iec")
    return 1


def read_text(path):
    """Return the text of path with LF line ends, or None (after a CHECK FAILED line) if it cannot be read."""
    try:
        with open(path, encoding="utf-8", newline="") as f:
            return f.read().replace("\r\n", "\n")
    except OSError as exc:
        print("gen_arity_table: CHECK FAILED: cannot read %s (%s)" % (os.path.basename(path), exc))
        return None


def check(max_n):
    arity_text = read_text(ARITY_FILE)
    arity_status = 1 if arity_text is None else check_arity(arity_text, max_n)
    node_text = read_text(NODE_FILE)
    node_status = 1 if node_text is None else check_nodes(node_text)
    ld_status = check_ld()
    return 1 if arity_status or node_status or ld_status else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--max", type=int, default=32, dest="max_n",
                        help="largest N in the arity table (1..32, default 32)")
    parser.add_argument("--nodes", action="store_true", help="print the node table instead of the arity table")
    parser.add_argument("--ld", action="store_true", help="print the generated part of rungiec_ld.iec instead")
    parser.add_argument("--check", action="store_true",
                        help="compare the arity table with rungiec_st.iec, the node table with rungiec.iec and "
                             "the generated part with rungiec_ld.iec")
    args = parser.parse_args()
    if not 1 <= args.max_n <= ARITY_HARD_MAX:
        parser.error("--max must be 1..%d" % ARITY_HARD_MAX)
    if args.check:
        return check(args.max_n)
    if args.ld:
        sys.stdout.write("\n".join(generate_ld()) + "\n")
        return 0
    if args.nodes:
        sys.stdout.write("\n".join(generate_nodes()) + "\n")
        return 0
    sys.stdout.write("\n".join(generate(args.max_n)) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
